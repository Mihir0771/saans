import { execSync } from "node:child_process";
import fs from "node:fs";
import path from "node:path";

export function buildReportMarkdown(results) {
  const commit = (() => {
    try {
      return execSync("git rev-parse --short HEAD", { encoding: "utf8" }).trim();
    } catch {
      return "uncommitted";
    }
  })();

  const rows = results.checks
    .map(
      (c) =>
        `| ${c.name} | ${c.passed ? "PASS" : "FAIL"} | ${c.durationMs} ms | ${c.summary.replace(/\|/g, "/")} |`,
    )
    .join("\n");

  return `# Verification Report — Saans

Generated by \`npm run verify\` from real command outputs only.

- **Timestamp:** ${results.timestamp}
- **Git commit:** \`${commit}\`
- **Node version:** ${process.version}
- **Overall:** ${results.allPassed ? "PASS" : "FAIL"}

## Checks Summary

| Check | Status | Duration | Details |
|---|---|---|---|
${rows}

## Coverage & Metrics

${results.metricsBlock}
`;
}

export function writeReport(results) {
  const md = buildReportMarkdown(results);
  fs.writeFileSync(path.resolve("VERIFICATION_REPORT.md"), md, "utf8");
}
